type BodyData = typeof FRONT_BODY;

function renderPaths(
  data: BodyData,
  activeSet: Set<string>,
  color: string,
) {
  return Object.values(data).map((group) => {
    const isBase = (group as {base?:boolean}).base;
    const isActive = !isBase && activeSet.has(group.slug);
    const fillColor = isBase
      ? ((group as {color?:string}).color ?? 'var(--s3)')
      : isActive ? color : 'var(--s3)';
    const opacity = isBase ? 1 : isActive ? 0.82 : 0.2;
    const paths = [
      ...((group as {common?:string[]}).common ?? []),
      ...((group as {left?:string[]}).left ?? []),
      ...((group as {right?:string[]}).right ?? []),
    ];
    return paths.map((d, i) => (
      <motion.path
        key={`${group.slug}-${i}`}
        d={d}
        fill={fillColor}
        initial={{ opacity: 0 }}
        animate={{ opacity }}
        transition={{ duration: 0.3, delay: isActive ? i * 0.02 : 0 }}
      />
    ));
  });
}

